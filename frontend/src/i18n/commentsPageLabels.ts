export function getCommentsPageFallback(text: string, locale: string): string | null {
    const key = (Object.keys(commentsPageFrench) as Array<keyof CommentsLabels>)
        .find(key => commentsPageFrench[key] === text);
    return key ? commentsPageTranslations[locale.toLowerCase().split("-")[0]]?.[key] ?? null : null;
}
