const sourceEntries = Object.entries(PAGE_UI_SOURCES_FR) as Array<[keyof typeof PAGE_UI_SOURCES_FR, string]>;
const sourceKeys = new Map(sourceEntries.map(([key, source]) => [source, key]));
const templates = sourceEntries.filter(([, source]) => /\{\w+\}/.test(source)).map(([key, source]) => {
    const fields: string[] = [];
    const escaped = source.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const pattern = escaped.replace(/\\\{(\w+)\\\}/g, (_, field: string) => {
        fields.push(field);
        return "(.+?)";
    });
    return { key, fields, expression: new RegExp("^" + pattern + "$", "s") };
});

// Only approved local UI sources/templates are translated. Captured values stay intact.
export function localizePageUiLabel(sourceFr: string, locale: string, exactOnly = false): string | null {
    const language = locale.split("-")[0];
    const translated = language === "fr" ? PAGE_UI_SOURCES_FR : PAGE_UI_TRANSLATIONS[language];
    if (!translated) return null;
    const key = sourceKeys.get(sourceFr);
    if (key) return translated[key];
    if (exactOnly) return null;
    for (const template of templates) {
        const match = template.expression.exec(sourceFr);
        if (!match) continue;
        return translated[template.key].replace(/\{(\w+)\}/g, (token, field: string) => {
            const index = template.fields.indexOf(field);
            return index < 0 ? token : match[index + 1];
        });
    }
    return null;
}

export function translateUiLabelTree<T>(value: T, t: (source: string) => string): T {
    if (typeof value === "string") return t(value) as T;
    if (Array.isArray(value)) return value.map(item => translateUiLabelTree(item, t)) as T;
    if (value && typeof value === "object") {
        return Object.fromEntries(Object.entries(value).map(([key, item]) =>
            [key, translateUiLabelTree(item, t)])) as T;
    }
    return value;
}

export function formatUiDate(value: string, locale: string): string {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return value;
    const date = new Date(`${value}T00:00:00Z`);
    return Number.isNaN(date.getTime()) ? value : date.toLocaleDateString(locale, { timeZone: "UTC" });
}

export function formatUiTime(value: string, locale: string): string {
    if (!/^([01]\d|2[0-3]):[0-5]\d$/.test(value)) return value;
    return new Date(`1970-01-01T${value}:00Z`).toLocaleTimeString(locale, {
        hour: "2-digit", minute: "2-digit", timeZone: "UTC",
    });
}
