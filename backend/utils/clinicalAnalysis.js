const DEFAULT_DIAGNOSIS_SUSPECTED = "Clinical analysis in progress";
const DEFAULT_DIAGNOSIS_CERTAINTY = "moderate";
const DEFAULT_DIAGNOSIS_JUSTIFICATION =
    "Analysis based on the available clinical data.";
const DEFAULT_PATIENT_SUMMARY_PLAIN = "Patient summary generated by ClinIA.";
const DEFAULT_PATIENT_SUMMARY_CLINICAL = "Structured clinical analysis.";
const DEFAULT_CONFIDENCE_SCORE = 0.6;

const STANDARD_KEYS = new Set([
    "diagnosis",
    "treatments",
    "alternatives",
    "red_flags",
    "patient_summary",
    "meta",
]);

const KNOWN_AI_FIELDS = [
    "clinical_summary",
    "recommendations",
    "initial_evaluation_recommendations",
    "treatment_options",
    "follow_up_and_monitoring",
    "supportive_care",
    "follow_up_and_supportive_care",
];

function hasMeaningfulValue(value) {
    if (typeof value === "string") {
        return value.trim().length > 0;
    }

    if (Array.isArray(value)) {
        return value.some((entry) => hasMeaningfulValue(entry));
    }

    if (value && typeof value === "object") {
        return Object.values(value).some((entry) => hasMeaningfulValue(entry));
    }

    return value !== null && value !== undefined;
}

function toStringArray(value) {
    if (!Array.isArray(value)) {
        return [];
    }

    return value
        .map((entry) => String(entry ?? "").trim())
        .filter(Boolean);
}

const OPTION_EXTRA_FIELDS = ["id", "class", "shortName", "summary", "details", "rationale", "explanation", "references", "sources", "source_fields"];
function authoredOptionFields(option) {
    if (!option || typeof option !== "object") return {};
    const mapped = Object.fromEntries(OPTION_EXTRA_FIELDS.filter(key => option[key] !== undefined).map(key => [key, option[key]]));
    const standard = new Set(["name", "indication", "justification", "dosage", "duration", "contraindications", "monitoring", "evidence_level", "id", "shortName", "class", "flags", "source_fields"]);
    const textFields = new Set(["indication", "justification", "dosage", "duration", "summary", "details"]);
    const remaining = Object.fromEntries(Object.entries(option).filter(([key, value]) => !standard.has(key) || (textFields.has(key) && typeof value !== "string")));
    if (!mapped.source_fields && Object.keys(remaining).length) mapped.source_fields = remaining;
    for (const key of ["summary", "details", "class", "shortName"]) {
        if (mapped[key] !== undefined && typeof mapped[key] !== "string") delete mapped[key];
    }
    return mapped;
}

function firstAuthoredText(...values) {
    return values.find(value => typeof value === "string" && value.trim()) ?? "";
}

function buildTreatmentFromString(name, extras = {}) {
    return {
        ...authoredOptionFields(extras),
        ...(extras.justification !== undefined ? { justification: firstAuthoredText(extras.justification) } : {}),
        name: String(name || "Unspecified treatment").trim() || "Unspecified treatment",
        indication: firstAuthoredText(extras.indication),
        dosage: firstAuthoredText(extras.dosage),
        duration: firstAuthoredText(extras.duration),
        contraindications: toStringArray(extras.contraindications),
        monitoring: toStringArray(extras.monitoring),
        evidence_level: extras.evidence_level ?? "C",
    };
}

function flattenTherapeuticOptions(therapeuticOptions) {
    if (!therapeuticOptions || typeof therapeuticOptions !== "object") {
        return [];
    }

    const treatments = [];
    if (Array.isArray(therapeuticOptions.lifestyle_modifications)) {
        for (const item of therapeuticOptions.lifestyle_modifications) {
            if (typeof item === "string" && item.trim()) {
                treatments.push(
                    buildTreatmentFromString(item, {
                        indication: "Lifestyle modification",
                    })
                );
            }
        }
    }

    if (Array.isArray(therapeuticOptions.pharmacologic_treatment)) {
        for (const option of therapeuticOptions.pharmacologic_treatment) {
            const firstLineAgents = toStringArray(option?.first_line_agents);
            for (const agent of firstLineAgents) {
                treatments.push(
                    buildTreatmentFromString(agent, {
                        indication:
                            typeof option?.selection_considerations === "string"
                                ? option.selection_considerations
                                : "Pharmacologic treatment",
                        ...authoredOptionFields(option),
                        ...(option?.justification !== undefined || option?.rationale !== undefined
                            ? { justification: option.justification ?? option.rationale } : {}),
                        // These fields are authored on this option, never inferred
                        // from the analysis-wide context or a medication name.
                        contraindications: option?.contraindications,
                        monitoring: option?.monitoring,
                    })
                );
            }
        }
    }

    return treatments;
}

function namedStructuredOptions(value) {
    if (!value || typeof value !== "object") return [];
    if (Array.isArray(value)) return value.flatMap(option => {
        // Arrays here are authored option lists, not a recursive scan of all
        // nested .name fields (references and monitoring are not treatments).
        return option && typeof option === "object" && !Array.isArray(option)
            && typeof option.name === "string" && option.name.trim()
            ? namedStructuredOptions(option) : [];
    });
    if (typeof value.name === "string" && value.name.trim()) {
        return [buildTreatmentFromString(value.name, {
            ...value,
            source_fields: value,
            justification: firstAuthoredText(value.justification, value.rationale, value.explanation),
        })];
    }
    const containers = ["options", "treatments", "medications", "pharmacologic_treatment", "pharmacologic_options", "pharmacological", "non_pharmacologic_options", "nonpharmacological", "lifestyle_modifications"];
    return containers.flatMap(key => namedStructuredOptions(value[key]));
}

// Old cache entries may contain a normalized copy of analysis-wide lists on
// every derived option. Repair only the complete, exact legacy shape, with
// the original therapeutic_options still present. Never guess by drug/class.
function matchesLegacyDerivedTreatments(treatments, derived, context) {
    if (!Array.isArray(treatments) || !derived.length || treatments.length !== derived.length) return false;
    const contraindications = toStringArray(context.contraindications ? Object.values(context.contraindications) : []);
    const monitoring = toStringArray(context.monitoring_considerations ? Object.values(context.monitoring_considerations) : []);
    if (!contraindications.length && !monitoring.length) return false;
    return treatments.every((treatment, index) => {
        if (!treatment || typeof treatment !== "object") return false;
        const { name, indication, dosage, duration, evidence_level } = derived[index];
        const expected = { name, indication, dosage, duration, evidence_level, contraindications, monitoring };
        const allowed = new Set([...Object.keys(expected), "justification"]);
        return Object.keys(treatment).every(key => allowed.has(key))
            && (treatment.justification === undefined || treatment.justification === "")
            && Object.entries(expected).every(([key, value]) => JSON.stringify(treatment[key]) === JSON.stringify(value));
    });
}

export function extractPrimaryClinicalConcern({ diagnosis, symptoms = [] } = {}) {
    if (typeof diagnosis === "string" && diagnosis.trim()) {
        return diagnosis.trim();
    }

    const safeSymptoms = Array.isArray(symptoms)
        ? symptoms.filter((entry) => typeof entry === "string")
        : [];

    for (const symptom of safeSymptoms) {
        const match = symptom.match(/(?:^|\|)\s*Main symptom:\s*([^|]+)/i);
        if (match?.[1]?.trim()) {
            return match[1].trim();
        }
    }

    return safeSymptoms.join(" ").trim();
}

export function normalizeClinicalAnalysis(
    raw,
    {
        model = process.env.OPENAI_MODEL ?? "fallback",
        primaryConcern = "",
        repairLegacyDerivedTreatments = false,
    } = {}
) {
    const pa = raw?.patient_analysis ?? {};
    const root = { ...raw };
    delete root.patient_analysis;
    const liftedOtherAIFields =
        raw?.other_ai_fields && typeof raw.other_ai_fields === "object"
            ? raw.other_ai_fields
            : {};

    const merged = { ...liftedOtherAIFields, ...root, ...pa };

    const mappedTherapeuticTreatments = flattenTherapeuticOptions(merged.therapeutic_options);
    const structuredTreatments = namedStructuredOptions(merged.treatment_options);

    const explicitTreatments = Array.isArray(merged.treatments)
        ? merged.treatments.map((treatment) => ({
            ...authoredOptionFields(treatment),
            name: treatment?.name ?? "Unspecified treatment",
            indication: firstAuthoredText(treatment?.indication),
            // Preserve authored rationale as its own field; do not reinterpret
            // it as an indication or generate replacement clinical content.
            justification: firstAuthoredText(treatment?.justification, treatment?.rationale, treatment?.explanation),
            dosage: firstAuthoredText(treatment?.dosage),
            duration: firstAuthoredText(treatment?.duration),
            contraindications: Array.isArray(treatment?.contraindications)
                ? treatment.contraindications
                : [],
            monitoring: Array.isArray(treatment?.monitoring)
                ? treatment.monitoring
                : [],
            evidence_level: treatment?.evidence_level ?? "C",
        }))
        : [];

    const repairLegacy = repairLegacyDerivedTreatments
        && matchesLegacyDerivedTreatments(merged.treatments, mappedTherapeuticTreatments, merged);
    const treatments = explicitTreatments.length > 0 && !repairLegacy
        ? explicitTreatments
        : mappedTherapeuticTreatments.length > 0
            ? mappedTherapeuticTreatments
            : structuredTreatments;

    const patientSummaryPlain =
        typeof merged.patient_summary === "string"
            ? merged.patient_summary
            : merged.patient_summary?.plain_language;
    const patientSummaryClinical =
        typeof merged.clinical_summary === "string"
            ? merged.clinical_summary
            : merged.patient_summary?.clinical_language;
    const normalizedPrimaryConcern =
        typeof primaryConcern === "string" && primaryConcern.trim()
            ? primaryConcern.trim()
            : "";
    const suspectedDiagnosis =
        merged.diagnosis?.suspected ??
        (normalizedPrimaryConcern || DEFAULT_DIAGNOSIS_SUSPECTED);

    const base = {
        diagnosis: {
            suspected: suspectedDiagnosis,
            certainty_level:
                merged.diagnosis?.certainty_level ?? DEFAULT_DIAGNOSIS_CERTAINTY,
            justification:
                merged.diagnosis?.justification ??
                DEFAULT_DIAGNOSIS_JUSTIFICATION,
        },
        treatments,
        alternatives: Array.isArray(merged.alternatives)
            ? merged.alternatives
            : [],
        red_flags: Array.isArray(merged.red_flags) ? merged.red_flags : [],
        patient_summary: {
            plain_language:
                patientSummaryPlain ??
                DEFAULT_PATIENT_SUMMARY_PLAIN,
            clinical_language:
                patientSummaryClinical ??
                DEFAULT_PATIENT_SUMMARY_CLINICAL,
        },
        meta: {
            model,
            confidence_score:
                typeof merged.confidence_score === "number"
                    ? merged.confidence_score
                    : DEFAULT_CONFIDENCE_SCORE,
        },
    };

    for (const key of KNOWN_AI_FIELDS) {
        if (Object.prototype.hasOwnProperty.call(merged, key)) {
            base[key] = merged[key];
        }
    }

    const otherAIFields = {};
    for (const [key, value] of Object.entries(merged)) {
        if (!STANDARD_KEYS.has(key) && !KNOWN_AI_FIELDS.includes(key) && value !== undefined) {
            otherAIFields[key] = value;
        }
    }

    if (Object.keys(otherAIFields).length > 0) {
        base.other_ai_fields = otherAIFields;
    }

    return base;
}

export function isPlaceholderClinicalAnalysis(analysis) {
    const normalized = normalizeClinicalAnalysis(analysis, {
        model: analysis?.meta?.model ?? process.env.OPENAI_MODEL ?? "fallback",
    });

    const hasAdvancedFields = KNOWN_AI_FIELDS.some((key) =>
        hasMeaningfulValue(normalized[key])
    ) || hasMeaningfulValue(normalized.other_ai_fields);

    return (
        normalized.diagnosis.suspected === DEFAULT_DIAGNOSIS_SUSPECTED &&
        normalized.diagnosis.certainty_level === DEFAULT_DIAGNOSIS_CERTAINTY &&
        normalized.diagnosis.justification === DEFAULT_DIAGNOSIS_JUSTIFICATION &&
        normalized.treatments.length === 0 &&
        normalized.alternatives.length === 0 &&
        normalized.red_flags.length === 0 &&
        normalized.patient_summary.plain_language === DEFAULT_PATIENT_SUMMARY_PLAIN &&
        normalized.patient_summary.clinical_language === DEFAULT_PATIENT_SUMMARY_CLINICAL &&
        !hasAdvancedFields
    );
}